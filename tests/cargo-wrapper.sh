#!/usr/bin/env bash
# Tests for scripts/cargo: each claim in its header, against a hostile crate. A scratch git repo
# gets a copy of scripts/cargo and a crate whose build.rs probes the container from inside
# (writes, mounts, limits, network) and records what it found in target/probe.txt. Then the
# attacks the reviews found are replayed: a symlinked or tracked target, a cargo alias for
# fmt and clippy, a rust-toolchain.toml that points at code in the repo.
# Uses the image and crate-cache volume of scripts/cargo (made on first use, which needs
# network); the crate has no dependencies, so nothing else is downloaded.
# Prints "  ok    NAME" / "  FAIL  NAME" per check; exit 0 only when all passed.
#   tests/cargo-wrapper.sh
# Each check is a single-quoted condition that ok() evals later: no expansion is meant there,
# and variables such as rc are read only inside those conditions.
# shellcheck disable=SC2016,SC2034
set -uo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
S=$(mktemp -d) || exit 2
trap 'rm -rf "$S"' EXIT
fail=0
ok() { if eval "$2"; then echo "  ok    $1"; else echo "  FAIL  $1   [$2]"; fail=$((fail + 1)); fi; }
probe() { grep "^$1 " "$S/target/probe.txt" 2> /dev/null | cut -d' ' -f2-; }

# The scratch repo: this checkout's wrapper and toolchain file, and the probe crate.
mkdir -p "$S/scripts" "$S/src"
cp "$HERE/scripts/cargo" "$S/scripts/cargo"
cp "$HERE/rust-toolchain.toml" "$S/"
cat > "$S/Cargo.toml" << 'E'
[package]
name = "probe"
version = "0.0.0"
edition = "2024"
build = "build.rs"
E
echo 'fn main() {}' > "$S/src/main.rs"
cat > "$S/build.rs" << 'E'
use std::fs;
fn main() {
    // Runs on every build: a file that never exists.
    println!("cargo:rerun-if-changed=/nonexistent-so-always-rerun");
    let w = |p: &str| match fs::write(p, b"x") {
        Ok(()) => "WRITABLE".to_string(),
        Err(e) => format!("denied-{:?}", e.kind()),
    };
    let seen = |p: &str| if fs::metadata(p).is_ok() { "VISIBLE" } else { "hidden" };
    let read = |p: &str| fs::read_to_string(p).unwrap_or_default().trim().to_string();
    let mut r = String::new();
    r += &format!("src-write {}\n", w("/src/PLANTED"));
    r += &format!("registry-write {}\n", w("/cargo/registry/PLANTED"));
    r += &format!("git-config {}\n", seen("/src/.git/config"));
    r += &format!("persist {}\n", if fs::metadata("/cargo/PERSIST").is_ok() { "SURVIVED" } else { "fresh" });
    let _ = fs::write("/cargo/PERSIST", b"x");
    r += &format!("memory.max {}\n", read("/sys/fs/cgroup/memory.max"));
    r += &format!("pids.max {}\n", read("/sys/fs/cgroup/pids.max"));
    let addr = "1.1.1.1:443".parse().unwrap();
    let net = std::net::TcpStream::connect_timeout(&addr, std::time::Duration::from_secs(2)).is_ok();
    r += &format!("network {}\n", if net { "REACHABLE" } else { "none" });
    fs::write("/target/probe.txt", r).unwrap();
}
E
cd "$S" || exit 2
git init -q && git add -A && git -c user.name=t -c user.email=0+test@users.noreply.github.com commit -qm init
C=$S/scripts/cargo

echo "== network mode returns only a Cargo.lock"
"$C" generate-lockfile > /dev/null 2>&1
ok "Cargo.lock made" '[ -f Cargo.lock ] && head -1 Cargo.lock | grep -q "@generated by Cargo"'
ok "no temp file left" '[ -z "$(ls -A | grep "^\.Cargo\.lock\.")" ]'
git add Cargo.lock && git -c user.name=t -c user.email=0+test@users.noreply.github.com commit -qm lock

echo "== build mode, from inside"
"$C" build > "$S/out" 2>&1
ok "build ran"                 '[ -f target/probe.txt ]'
ok "source read-only"          '[ "$(probe src-write)" = denied-ReadOnlyFilesystem ] && [ ! -e PLANTED ]'
ok "crate cache read-only"     '[ "$(probe registry-write)" = denied-ReadOnlyFilesystem ]'
ok ".git hidden"               '[ "$(probe git-config)" = hidden ]'
ok "memory capped at 4 GiB"    '[ "$(probe memory.max)" = 4294967296 ]'
ok "pids capped at 1024"       '[ "$(probe pids.max)" = 1024 ]'
ok "no network"                '[ "$(probe network)" = none ]'
"$C" build > "$S/out" 2>&1
ok "CARGO_HOME fresh each run" '[ "$(probe persist)" = fresh ]'

echo "== refusals"
"$C" -v build > /dev/null 2>&1
ok "leading option refused (rc 2)" '[ $? = 2 ]'
rm -rf target && ln -s . target
"$C" build > "$S/out" 2>&1; rc=$?
ok "symlinked target refused"  '[ $rc = 2 ] && grep -q "target is a symlink" "$S/out" && [ ! -e PLANTED ]'
rm -f target && mkdir target && echo x > target/keep && git add -f target/keep
"$C" build > "$S/out" 2>&1; rc=$?
ok "tracked target refused"    '[ $rc = 2 ] && grep -q "git tracks target" "$S/out"'
git rm -q --cached target/keep && rm -rf target

echo "== a cargo alias cannot replace fmt or clippy"
mkdir -p .cargo && printf '[alias]\nfmt = ["build"]\nclippy = ["version"]\n' > .cargo/config.toml
"$C" fmt > "$S/out" 2>&1
ok "fmt ran rustfmt, not the alias" '[ ! -e target/probe.txt ] && [ ! -e PLANTED ]'
"$C" clippy > "$S/out" 2>&1
ok "clippy ran clippy, not the alias" 'grep -q "Finished" "$S/out" && ! grep -q "^cargo 1\." "$S/out"'
rm -rf .cargo target

echo "== a rust-toolchain.toml cannot pick code in the repo"
mkdir -p tc/bin && printf '#!/bin/sh\ntouch /target/TC-RAN /tmp/TC-RAN 2>/dev/null\nexit 1\n' > tc/bin/cargo && chmod +x tc/bin/cargo
cp tc/bin/cargo tc/bin/rustc
printf '[toolchain]\npath = "/src/tc"\n' > rust-toolchain.toml
"$C" build > "$S/out" 2>&1; rc=$?
ok "build mode uses the pinned toolchain" '[ $rc = 0 ] && [ ! -e target/TC-RAN ]'
"$C" generate-lockfile > "$S/out" 2>&1; rc=$?
ok "network mode uses the pinned toolchain" '[ $rc = 0 ] && [ ! -e target/TC-RAN ]'

echo "cargo-wrapper: $fail failed"
[ "$fail" = 0 ]
